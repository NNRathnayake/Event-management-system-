    private void undobtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_undobtnActionPerformed
    if (!undoStack.isEmpty()) {
        JPanel panel = undoStack.pop();
        scrollPanel.add(panel, 0); // restore at top
        scrollPanel.revalidate();
        scrollPanel.repaint();
        redoStack.push(panel);
    } else {
        JOptionPane.showMessageDialog(this, "Nothing to undo");
    }
    }//GEN-LAST:event_undobtnActionPerformed

    private void redoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_redoActionPerformed
        if (!redoStack.isEmpty()) {
        JPanel panel = redoStack.pop();
        scrollPanel.remove(panel); // remove again
        scrollPanel.revalidate();
        scrollPanel.repaint();
        undoStack.push(panel);
    } else {
        JOptionPane.showMessageDialog(this, "Nothing to redo");
    }
    }//GEN-LAST:event_redoActionPerformed

