  private void loadActionLogs() {
        scrollPanel.removeAll();
        undoStack.clear();
        redoStack.clear();

        try (Connection conn = DBConnection.getConnection()) {
            String sql = "SELECT * FROM action_log ORDER BY log_id DESC";
            PreparedStatement ps = conn.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();

            while (rs.next()) {
                int userId = rs.getInt("user_id");
                String actionType = rs.getString("action_type");
                String eventId = rs.getString("event_id");
                Timestamp timestamp = rs.getTimestamp("action_time");

                JPanel card = createLogCard(userId, actionType, eventId, timestamp);
                scrollPanel.add(card);
                undoStack.push(card); // initial stack
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to load action logs: " + e.getMessage());
        }

        scrollPanel.revalidate();
        scrollPanel.repaint();
    }

 private JPanel createLogCard(int userId, String actionType, String eventId, Timestamp timestamp) {
    JPanel card = new JPanel();
    card.setBorder(BorderFactory.createLineBorder(Color.BLACK, 1));
    card.setMaximumSize(new Dimension(Integer.MAX_VALUE, 70));
    card.setLayout(new BorderLayout());

    JPanel info = new JPanel(new GridLayout(2,2));
    info.add(new JLabel("User ID: " + userId));
    info.add(new JLabel("Action: " + actionType));
    info.add(new JLabel("Event: " + (eventId != null ? eventId : "N/A")));
    info.add(new JLabel("Time: " + timestamp));

    JButton removeBtn = new JButton("Remove");
    removeBtn.addActionListener(e -> {
        // Remove from scroll panel
        scrollPanel.remove(card);
        scrollPanel.revalidate();
        scrollPanel.repaint();

        // Push to undoStack
        undoStack.push(card);

        // Clear redoStack (new action invalidates redo)
        redoStack.clear();
    });

    card.add(info, BorderLayout.CENTER);
    card.add(removeBtn, BorderLayout.EAST);

    return card;
}
  private void deleteLogEntry(String eventId, Timestamp time) {
    try (Connection conn = DBConnection.getConnection()) {

        String sql =
        "DELETE FROM action_log WHERE event_id=? AND action_time=?";

        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setString(1, eventId);
        ps.setTimestamp(2, time);

        ps.executeUpdate();

    } catch (Exception ex) {
        ex.printStackTrace();
    }
}  
    
    
